// CARROSSEL DE FOTOS
// ===================================================
let currentPhotoIndex = 0;
const totalPhotos = 3;

function moveCarousel(direction) {
  const galleryGrid = document.querySelector('.gallery-grid');
  if (!galleryGrid) return;

  currentPhotoIndex += direction;
  
  if (currentPhotoIndex >= totalPhotos) {
    currentPhotoIndex = 0;
  } else if (currentPhotoIndex < 0) {
    currentPhotoIndex = totalPhotos - 1;
  }
  
  updateCarousel(galleryGrid);
}

function goToPhoto(index) {
  const galleryGrid = document.querySelector('.gallery-grid');
  if (!galleryGrid) return;
  currentPhotoIndex = index;
  updateCarousel(galleryGrid);
}

function updateCarousel(galleryGrid) {
  const card = galleryGrid.querySelector('.gallery-card');
  if (card) {
    const cardWidth = card.offsetWidth + 16;
    galleryGrid.scrollLeft = currentPhotoIndex * cardWidth;
  }
  
  const indicators = document.querySelectorAll('.indicator');
  indicators.forEach((indicator, index) => {
    indicator.classList.toggle('active', index === currentPhotoIndex);
  });
}

